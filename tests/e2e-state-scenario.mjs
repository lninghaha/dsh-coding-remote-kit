/** Real app navigation, paging, transcript activity and approval focus scenarios. */
export async function stateRecoveryScenario() {
 const fixture = globalThis.__dshmrDraftE2e, results = {};
 const wait = async (condition, label) => {
  if (condition()) return;
  await new Promise((resolve, reject) => {
   const observer = new MutationObserver(() => { if (condition()) finish(); });
   const timer = setTimeout(() => { observer.disconnect(); reject(new Error(`State fixture: ${label}`)); }, 12_000);
   function finish() { clearTimeout(timer); observer.disconnect(); resolve(); }
   observer.observe(document.getElementById("app"), { subtree: true, childList: true, attributes: true, characterData: true });
   if (condition()) finish();
  });
 };
 const check = (name, ok) => { results[name] = Boolean(ok); if (!ok) throw new Error(`State assertion: ${name}`); };
 const composer = () => document.querySelector(".composer");
 const open = async (id) => {
  [...document.querySelectorAll(".bar button")].find((node) => node.textContent === "Back")?.click();
  await wait(() => document.querySelector(".ws-toggle"), "list");
  if (!document.querySelector(".task")) document.querySelector(".ws-toggle").click();
  const node = [...document.querySelectorAll(".task")].find((item) => item.textContent.includes(`Fixture ${id}`));
  if (!node) throw new Error(`Missing task ${id}`); node.click();
  await wait(() => composer() && document.querySelector(".bar").textContent.includes(`Fixture ${id}`), id);
 };
 const frame = () => new Promise((resolve) => requestAnimationFrame(() => resolve()));
 const rows = Array.from({ length: fixture.pageSize * 2 }, (_, index) => ({ seq: index + 1, event: { type: "assistant/message", data: { text: `A history ${index + 1}` } } }));
 fixture.setHistory("A", rows); fixture.setHistory("B", [{ seq: 1, event: { type: "assistant/message", data: { text: "B only" } } }]);
 fixture.mount({ host: "host-reading" }); await open("A");
 document.querySelector(".load-older").click();
 await wait(() => [...document.querySelectorAll(".transcript .bubble")].some((node) => node.textContent === "A history 1"), "older history");
 const scroller = document.querySelector(".transcript");
 scroller.scrollTop = Math.floor((scroller.scrollHeight - scroller.clientHeight) / 2);
 scroller.dispatchEvent(new Event("scroll")); const top = scroller.scrollTop;
 fixture.mount({ host: "host-reading" });
 await wait(() => composer() && [...document.querySelectorAll(".transcript .bubble")].some((node) => node.textContent === "A history 1"), "restore loaded range"); await frame();
 check("readingAndSessionRestored", document.querySelector(".bar").textContent.includes("Fixture A") && document.querySelector(".transcript").scrollTop === top);
 fixture.mount({ host: "host-growing" }); await open("A");
 const growing = document.querySelector(".transcript"); growing.scrollTop = Math.floor((growing.scrollHeight - growing.clientHeight) / 2); growing.dispatchEvent(new Event("scroll")); const growingTop = growing.scrollTop;
 const newer = Array.from({ length: fixture.pageSize / 2 }, (_, index) => ({ seq: rows.length + index + 1, event: { type: "assistant/message", data: { text: `New history ${index + 1}` } } }));
 fixture.setHistory("A", [...rows, ...newer]); fixture.mount({ host: "host-growing" });
 await wait(() => composer() && document.querySelector(".transcript")?.textContent.includes("New history"), "growing history restored"); await frame();
 check("growingHistoryKeepsOriginalPrefixAndReading", document.querySelector(".transcript .bubble").textContent === `A history ${fixture.pageSize + 1}` && document.querySelector(".transcript").scrollTop === growingTop);
 const missed = { seq: rows.length + newer.length + 1, event: { type: "assistant/message", data: { text: "Missed during mux interruption" } } };
 fixture.setHistory("A", [...rows, ...newer, missed]);
 const beforeCatchup = fixture.historyCalls.length;
 fixture.push({ push: "inbox.reset", data: {} }); fixture.push({ push: "session.subscribed", data: { sessionId: "A", lastSeq: missed.seq } });
 await wait(() => document.querySelector(".transcript")?.textContent.includes("Missed during mux interruption"), "mux history catchup");
 check("muxReopenRecoversMissingTranscript", fixture.historyCalls.length > beforeCatchup && document.querySelector(".transcript").scrollTop === growingTop);
 fixture.setHistory("A", rows); fixture.holdHistory(); fixture.mount({ host: "host-mux-initial" });
 await wait(() => document.querySelector(".ws-toggle"), "initial mux list"); document.querySelector(".ws-toggle").click(); document.querySelector(".task").click();
 await frame(); check("initialHistoryActuallyHeld", fixture.historyPending() === 1);
 fixture.setHistory("A", [...rows, missed]);
 fixture.push({ push: "inbox.reset", data: {} }); fixture.push({ push: "session.subscribed", data: { sessionId: "A", lastSeq: missed.seq } });
 fixture.releaseHistory();
 await wait(() => document.querySelector(".transcript")?.textContent.includes("Missed during mux interruption"), "initial mux history catchup");
 check("muxReopenDuringInitialHistoryRecoversGap", document.querySelector(".transcript").textContent.includes("Missed during mux interruption"));
 fixture.setHistory("A", rows);
 fixture.mount({ host: "host-live-paging" }); await open("A");
 const pagingScroller = document.querySelector(".transcript"); pagingScroller.scrollTop = Math.floor((pagingScroller.scrollHeight - pagingScroller.clientHeight) / 2);
 fixture.holdOlder(); document.querySelector(".load-older").click();
 check("sameSessionPageHeld", fixture.historyPending() === 1);
 fixture.push({ push: "session.event", data: { sessionId: "A", seq: rows.length + 1, event: { type: "assistant/message", data: { text: "Live while older page is pending" } } } });
 const beforeInsert = document.querySelector(".transcript"); beforeInsert.scrollTop += beforeInsert.querySelector(".bubble").clientHeight; beforeInsert.dispatchEvent(new Event("scroll"));
 const anchor = [...beforeInsert.querySelectorAll(".bubble")].find(node => node.getBoundingClientRect().top >= beforeInsert.getBoundingClientRect().top);
 const anchorText = anchor.textContent, anchorTop = anchor.getBoundingClientRect().top;
 fixture.releaseHistory(); await frame();
 const restoredAnchor = [...document.querySelectorAll(".transcript .bubble")].find(node => node.textContent === anchorText);
 // CSS scrollTop is quantized by the browser; compare within one physical pixel.
 check("pagingWithLiveAppendKeepsUserReading", Math.abs(restoredAnchor.getBoundingClientRect().top - anchorTop) < 1 / devicePixelRatio);
 fixture.mount({ host: "host-paging" }); await open("A"); fixture.holdOlder(); document.querySelector(".load-older").click();
 check("pageActuallyInFlight", fixture.historyPending() === 1);
 await open("B"); const bTop = document.querySelector(".transcript").scrollTop;
 fixture.releaseHistory(); await frame();
 check("oldPageIgnored", document.querySelector(".transcript").textContent.includes("B only") && !document.querySelector(".transcript").textContent.includes("A history") && document.querySelector(".transcript").scrollTop === bTop);
 await open("A"); fixture.holdOlder(); document.querySelector(".load-older").click(); await open("B"); fixture.releaseHistory("A-page-error"); await frame();
 check("oldPageErrorIgnored", !document.body.textContent.includes("A-page-error"));
 const emit = (seq, type, data) => fixture.push({ push: "session.event", data: { sessionId: "B", event: { seq, type, data } } });
 emit(2, "assistant/chunk", { text: "first-" }); emit(3, "assistant/chunk", { text: "second" }); emit(3, "assistant/chunk", { text: "second" });
 check("orderedDeduplicatedChunks", document.querySelector(".transcript").textContent.includes("first-second") && !document.querySelector(".transcript").textContent.includes("secondsecond"));
 emit(4, "tool/call", { name: "read", callId: "one" }); check("toolActive", document.querySelector(".activity-strip").textContent.includes("read"));
 const bubbleCount = document.querySelectorAll(".bubble").length;
 emit(5, "tool/result", { name: "read", callId: "one" });
 check("toolCompleteNoDuplicateBubble", document.querySelector(".activity-strip").textContent.includes("Tool completed") && document.querySelectorAll(".bubble").length === bubbleCount);
 emit(6, "tool/call", { name: "write", callId: "two" }); emit(7, "tool/error", { name: "write", callId: "two" });
 check("toolFailure", document.querySelector(".activity-strip").textContent.includes("Tool failed: write"));
 const approval = { push: "approval.requested", rpcId: "original-approval-rpc", data: { sessionId: "A", approvalId: "link-A", toolName: "read" } };
 fixture.setInbox([]); const consumed = fixture.consumed();
 fixture.mount({ host: "host-focus", focus: { sessionId: "A", approvalId: "link-A" } });
 await wait(() => composer() && document.body.textContent.includes("not available yet"), "unavailable notice");
 check("missingTargetRetained", fixture.consumed() === consumed);
 fixture.push({ push: "inbox.reset", data: {} }); fixture.push({ push: "session.subscribed", data: { sessionId: "A" } });
 await wait(() => document.body.textContent.includes("not available yet"), "missing target after repeated restore");
 check("missingTargetAfterResetExplained", fixture.consumed() === consumed);
 fixture.push(approval); await wait(() => fixture.consumed() === consumed + 1, "late approval focus"); await frame();
 const card = document.querySelector('[data-approval-id="link-A"]');
 check("lateReplayFocused", card !== null && card.contains(document.activeElement));
 card.querySelector("button").click(); await wait(() => fixture.replies.length > 0, "approval response");
 check("originalRpcIdUsed", fixture.replies.at(-1).rpcId === "original-approval-rpc");
 fixture.mount({ host: "host-resolved", focus: { sessionId: "A", approvalId: "resolved-A" } });
 fixture.push({ push: "approval.resolved", data: { sessionId: "A", approvalId: "resolved-A" } });
 await wait(() => document.body.textContent.includes("has been resolved"), "resolved notice");
 check("resolvedTargetExplained", !document.querySelector('[data-approval-id="resolved-A"]'));
 fixture.holdBaseline(); fixture.mount({ host: "host-snapshot-race" });
 fixture.push({ push: "approval.resolved", data: { sessionId: "A", approvalId: "link-A" } }); fixture.releaseBaseline([approval]);
 await wait(() => document.querySelector(".ws-toggle"), "snapshot completed");
 check("resolvedNotResurrectedBySnapshot", !document.querySelector('[data-approval-id="link-A"]'));
 fixture.setInbox(null); fixture.mount({ host: "host-legacy" });
 await wait(() => document.querySelector(".ws-toggle"), "legacy subscription");
 fixture.push(approval); check("legacySnapshotOptional", document.querySelector('[data-approval-id="link-A"]') !== null);
 fixture.push({ push: "inbox.reset", data: {} }); check("resetClearsInbox", document.querySelector('[data-approval-id="link-A"]') === null);
 fixture.push({ ...approval, rpcId: "same-A", data: { ...approval.data, approvalId: "same" } });
 fixture.push({ ...approval, rpcId: "same-B", data: { ...approval.data, sessionId: "B", approvalId: "same" } });
 check("sameApprovalIdAcrossSessionsSurvives", document.querySelectorAll('[data-approval-id="same"]').length === 2);
 fixture.push({ push: "approval.resolved", data: { sessionId: "A", approvalId: "same" } });
 check("resolvedApprovalDoesNotRemoveOtherSession", document.querySelectorAll('[data-approval-id="same"]').length === 1);
 fixture.dispose(); return results;
}
